const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch(); const ctx = await b.newContext({ viewport: { width: 420, height: 900 }, permissions: ['clipboard-read', 'clipboard-write'] });
  const p = await ctx.newPage(); const errs = []; let f = 0;
  p.on('pageerror', e => errs.push(e.message));
  const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) f++; };
  await p.goto('http://localhost:8770/index.html'); await p.waitForTimeout(400);
  await p.click('#menu'); await p.click('text=Ещё…'); await p.click('text=Подстановки в тексте'); await p.waitForTimeout(300);
  const out = async t => { await p.fill('.sheet textarea.field', t); await p.waitForTimeout(100); return p.locator('.sheet pre.pv').innerText(); };
  const d = new Date(), p2 = x => String(x).padStart(2, '0');
  const uMonths = ['січень','лютий','березень','квітень','травень','червень','липень','серпень','вересень','жовтень','листопад','грудень'];
  const uGen = ['січня','лютого','березня','квітня','травня','червня','липня','серпня','вересня','жовтня','листопада','грудня'];
  const uWd = ['неділя','понеділок','вівторок','середа','четвер','пʼятниця','субота'];
  ok(await out('{місяць}') === uMonths[d.getMonth()], 'місяць → ' + uMonths[d.getMonth()]);
  ok(await out('{день тижня}') === uWd[d.getDay()], 'день тижня');
  ok(await out('{рік}') === String(d.getFullYear()), 'рік');
  ok(/^\d\d:\d\d$/.test(await out('{час}')), 'час');
  ok(await out('{дата словами}') === d.getDate() + ' ' + uGen[d.getMonth()] + ' ' + d.getFullYear() + ' р.', 'дата словами');
  ok(/^\d\d\.\d\d$/.test(await out('{дата коротко}')), 'дата коротко');
  ok(await out('{сьогодні}') === p2(d.getDate()) + '.' + p2(d.getMonth() + 1) + '.' + d.getFullYear(), 'сьогодні');
  ok(/^\d\d\.\d\d\.\d{4}$/.test(await out('{вчора}')) && /^\d\d\.\d\d\.\d{4}$/.test(await out('{післязавтра}')), 'вчора, післязавтра');
  ok(await out('{ДАТА+7}') !== '{ДАТА+7}', 'дата+7 работает');
  const cap = x => x[0].toUpperCase() + x.slice(1);
  ok(await out('{Місяць}') === cap(uMonths[d.getMonth()]), 'Місяць → с большой: ' + await out('{Місяць}'));
  ok(await out('{МІСЯЦЬ}') === uMonths[d.getMonth()].toUpperCase(), 'МІСЯЦЬ → всё заглавными');
  ok(await out('{Месяц}') === cap(['январь','февраль','март','апрель','май','июнь','июль','август','сентябрь','октябрь','ноябрь','декабрь'][d.getMonth()]), 'Месяц → Ноябрь');
  ok(await out('{День тижня}') === cap(uWd[d.getDay()]), 'День тижня с большой');
  ok(await out('{День недели}') === cap(['воскресенье','понедельник','вторник','среда','четверг','пятница','суббота'][d.getDay()]), 'День недели с большой');
  ok(await out('{Год}') === String(d.getFullYear()) && await out('{Дата}') === p2(d.getDate()) + '.' + p2(d.getMonth() + 1) + '.' + d.getFullYear(), 'числовые не ломаются');
  ok(await out('{месяц}') !== uMonths[d.getMonth()] || d.getMonth() === 0 && false || true, 'русский месяц по-прежнему русский');
  ok(['январь','февраль','март','апрель','май','июнь','июль','август','сентябрь','октябрь','ноябрь','декабрь'].includes(await out('{месяц}')), '{месяц} остался по-русски');
  ok(await out('{часть}') === '{часть}', 'посторонние скобки не тронуты');
  ok(await out('{?Імʼя=Іван}') !== undefined, 'поле на украинском не падает');
  ok(errs.length === 0, 'нет ошибок ' + errs);
  await p.screenshot({ path: '/tmp/gm/uk.png' });
  console.log(f ? 'FAILS' : 'ALL OK'); await b.close();
})();
